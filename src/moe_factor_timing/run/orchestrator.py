"""Pipeline orchestrator: data -> features -> splits -> models -> evaluation -> report."""

from __future__ import annotations

import logging
import shutil
from datetime import datetime, timezone
from pathlib import Path

from ..backtest.engine import run_backtest
from ..config import Config, load_config
from ..data.loader import load_market_data
from ..data.validate import validate_market_data
from ..evaluation.evaluate import evaluate_suite
from ..features.build import build_features
from ..reporting.plots import generate_all_plots
from ..reporting.report import generate_report
from ..splits.walk_forward import make_walk_forward_splits
from ..utils.io import ensure_dir, write_csv, write_json, write_text
from ..utils.logging import configure_logging
from ..utils.paths import resolve_path
from ..utils.seeds import set_global_seed
from .manifest import write_manifest

logger = logging.getLogger(__name__)


class PipelineError(RuntimeError):
    """Raised when a contract check fails and the run must stop."""


def _make_run_id() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def run_pipeline(
    config_path: str | Path,
    run_id: str | None = None,
    publish: bool = False,
) -> Path:
    config: Config = load_config(config_path)
    configure_logging()
    set_global_seed(config.run.seed)

    identifier = run_id or config.run.id or _make_run_id()
    run_dir = ensure_dir(resolve_path(config.output.runs_dir) / identifier)
    if any(run_dir.iterdir()):
        raise FileExistsError(f"run directory is not empty: {run_dir}")
    logger.info("run directory: %s", run_dir)

    config_copy = run_dir / "config.yaml"
    config_copy.write_text(config.source_path.read_text(encoding="utf-8"), encoding="utf-8")
    write_json(run_dir / "config_resolved.json", config.to_dict())

    # 1. Data
    logger.info("[1/8] loading reference data")
    market = load_market_data(config)
    validation = validate_market_data(market, config)
    write_json(run_dir / "validation.json", validation.to_dict())
    if not validation.passed:
        failed = [check.name for check in validation.checks if not check.passed]
        raise PipelineError(f"data validation failed: {failed}")
    data_dir = ensure_dir(run_dir / "data")
    factors_out = market.factors.copy()
    factors_out.index.name = "date"
    write_csv(data_dir / "factors.csv", factors_out)
    rf_out = market.risk_free.rename("RF").to_frame()
    rf_out.index.name = "date"
    write_csv(data_dir / "risk_free.csv", rf_out)
    write_json(data_dir / "data_manifest.json", market.metadata)
    logger.info(
        "data: %s to %s (%d rows)", market.start.date(), market.end.date(), len(market.factors)
    )

    # 2. Features
    logger.info("[2/8] building features")
    features = build_features(market, config)
    features.save(run_dir / "features")
    logger.info(
        "features: %d rows, %d features, %d targets",
        features.X.shape[0],
        features.X.shape[1],
        features.y.shape[1],
    )

    # 3. Splits
    logger.info("[3/8] creating walk-forward splits")
    split_plan = make_walk_forward_splits(features.decision_dates, features.target_dates, config)
    write_json(run_dir / "splits" / "plan.json", split_plan.to_dict())
    logger.info(
        "splits: %d decisions, %d holdout",
        len(split_plan.splits),
        sum(split.is_holdout for split in split_plan.splits),
    )

    # 4-6. Models, decisions, backtest
    logger.info("[4-6/8] running models and backtest")
    suite = run_backtest(market, features, split_plan, config)
    suite.save(run_dir)

    # 7. Evaluation
    logger.info("[7/8] evaluating")
    evaluation = evaluate_suite(suite, config)
    evaluation.save(run_dir / "evaluation")

    # 8. Report and figures
    logger.info("[8/8] generating report")
    report_dir = ensure_dir(run_dir / "report")
    if config.output.save_plots:
        generate_all_plots(suite, report_dir / "figures")
    generate_report(
        suite=suite,
        evaluation=evaluation,
        config=config,
        run_id=identifier,
        run_dir=run_dir,
        report_path=report_dir / "report.md",
    )
    write_text(
        run_dir / "README.md",
        "# Run " + identifier + "\n\n"
        f"Generated by `moe-factor-timing` at {datetime.now(timezone.utc).isoformat()}.\n\n"
        "Start with `report/report.md`; the machine-readable results are in "
        "`evaluation/`, and `manifest.json` binds every artifact to the config, "
        "data snapshot, and code state.\n",
    )

    # Manifest last, so it hashes everything else.
    manifest_path = write_manifest(
        run_dir=run_dir,
        config=config,
        data_metadata=market.metadata,
        validation=validation.to_dict(),
        evaluation_meta=evaluation.meta,
    )
    logger.info("manifest: %s", manifest_path)

    if publish:
        publish_report(run_dir, config)

    logger.info("run complete: %s", run_dir)
    return run_dir


def publish_report(run_dir: Path, config: Config) -> None:
    """Copy the curated report and figures into ``reports/`` for version control."""
    reports_dir = ensure_dir(resolve_path(config.output.reports_dir))
    report_source = run_dir / "report" / "report.md"
    if report_source.exists():
        shutil.copy2(report_source, reports_dir / "v2_report.md")
    figures_source = run_dir / "report" / "figures"
    if figures_source.exists():
        figures_target = ensure_dir(reports_dir / "figures")
        for path in sorted(figures_source.glob("*.png")):
            shutil.copy2(path, figures_target / path.name)
    metrics_source = run_dir / "evaluation" / "metrics.csv"
    if metrics_source.exists():
        shutil.copy2(metrics_source, reports_dir / "metrics.csv")
    holdout_source = run_dir / "evaluation" / "holdout_metrics.csv"
    if holdout_source.exists():
        shutil.copy2(holdout_source, reports_dir / "holdout_metrics.csv")
